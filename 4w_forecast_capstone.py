def normalize_name(value):
    # Match both a literal "\\n" and an actual newline, plus the FX suffix alias.
    s = str(value).replace("\\n", " ").replace("\n", " ")
    s = s.replace("_(Month_End)", "").replace("(Month_End)", "")
    return re.sub(r"[\s_]+", "", s).casefold()

def numeric(series):
    if pd.api.types.is_numeric_dtype(series):
        return pd.to_numeric(series, errors="coerce").replace([np.inf, -np.inf], np.nan)
    s = series.astype("string").str.strip().str.replace(",", "", regex=False)
    s = s.str.replace("₹", "", regex=False).str.replace("−", "-", regex=False)
    s = s.str.replace(r"^\(([-\d.]+)\)$", r"-\1", regex=True)
    return pd.to_numeric(s, errors="coerce").replace([np.inf, -np.inf], np.nan)

def parse_dates(series):
    if pd.api.types.is_datetime64_any_dtype(series):
        return pd.to_datetime(series)
    s = series.astype("string").str.strip()
    result = pd.to_datetime(s, format="%b-%Y", errors="coerce")
    for fmt in ["%Y-%m-%d", "%Y-%m", "%b %Y", "%B-%Y", "%d/%m/%Y"]:
        missing = result.isna()
        result.loc[missing] = pd.to_datetime(s.loc[missing], format=fmt, errors="coerce")
    return result

def load_data(path, args):
    path = Path(path)
    raw = pd.read_csv(path) if path.suffix.lower() == ".csv" else pd.read_excel(path, sheet_name=args.sheet)
    if raw.columns.duplicated().any():
        raise ValueError("Duplicate source column names must be corrected.")
    names = {normalize_name(c): c for c in raw.columns}
    def resolve(preferred, alternatives):
        for c in [preferred] + alternatives:
            if normalize_name(c) in names:
                return names[normalize_name(c)]
        raise ValueError(f"Cannot find {preferred!r}; available columns: {list(raw.columns)}")
    date_col = resolve(args.date_col, ["Period", "Date", "Month_Date"])
    target_col = resolve(args.target_col, ["Registrations", "Demand", "Sales"])
    date = parse_dates(raw[date_col]).dt.to_period("M").dt.to_timestamp()
    if date.isna().any():
        raise ValueError(f"Unparseable dates: {raw.loc[date.isna(), date_col].head().tolist()}")
    d = raw.copy()
    d["__date"] = date
    target = numeric(d[target_col])
    if ((d[target_col].notna()) & target.isna()).any():
        bad = d.loc[d[target_col].notna() & target.isna(), target_col].unique()[:5]
        raise ValueError(f"Non-numeric target values {bad}; clean them explicitly.")
    if (target.dropna() < 0).any():
        raise ValueError("Negative registrations require correction before forecasting.")
    d["__target"] = target
    quality = d.groupby("__date")["__target"].agg(["count", "size"])
    quality["missing_target_rows"] = quality["size"] - quality["count"]
    # min_count=1 prevents an entirely absent month being silently converted to zero.
    monthly = d.groupby("__date")["__target"].sum(min_count=1).rename("Demand").to_frame()
    full_index = pd.date_range(monthly.index.min(), monthly.index.max(), freq="MS")
    monthly = monthly.reindex(full_index)
    monthly.index.name = "Month"
    if monthly.Demand.isna().any():
        raise ValueError("Missing monthly target totals: " + ", ".join(monthly.index[monthly.Demand.isna()].strftime("%Y-%m")))
    if (quality.missing_target_rows > 0).any():
        LOG.warning("Some maker-level registration cells are blank. Totals sum reported values only; inspect Target_Coverage and source coverage. Blanks are not recoded as observed zeros.")
    column_audit, candidates, conflicts = [], [], []
    excluded = {date_col, target_col, "Maker", "Year", "Month", "date", "Date"}
    for c in raw.columns:
        if c in excluded:
            column_audit.append({"Column": c, "Role": "identifier/target", "Numeric_months": np.nan})
            continue
        values = numeric(raw[c])
        if not values.notna().any():
            column_audit.append({"Column": c, "Role": "preserved source; nonnumeric or entirely missing", "Numeric_months": 0})
            continue
        temp = pd.DataFrame({"date": date, "value": values})
        n_unique = temp.groupby("date").value.nunique()
        if (n_unique > 1).any():
            conflicts.append({"Column": c, "Conflicting_months": int((n_unique > 1).sum())})
            column_audit.append({"Column": c, "Role": "not a unique national monthly predictor", "Numeric_months": int(temp.groupby("date").value.first().notna().sum())})
            continue
        monthly[c] = temp.groupby("date").value.first().reindex(monthly.index)
        candidates.append(c)
        column_audit.append({"Column": c, "Role": "available monthly predictor", "Numeric_months": int(monthly[c].notna().sum())})
    resolved_core = [names[normalize_name(c)] for c in CORE_MACROS if normalize_name(c) in names and names[normalize_name(c)] in candidates]
    if args.macro_cols:
        macros = []
        for c in args.macro_cols:
            match = names.get(normalize_name(c))
            if match not in candidates:
                raise ValueError(f"Selected macro {c!r} is absent, empty or not unique within month.")
            macros.append(match)
    elif args.macro_set == "all":
        macros = candidates.copy()
    else:
        macros = resolved_core
        if len(macros) != 6:
            LOG.warning("Resolved %d/6 core macro variables. See column audit; missing variables are not invented.", len(macros))
    macros = list(dict.fromkeys(macros))
    if not macros:
        raise ValueError("No usable macro variables. Check column names or --macro-cols.")
    for row in column_audit:
        if row["Column"] in macros:
            row["Role"] = "selected macro predictor"
    available_months = len(monthly)
    if args.history_months:
        if args.history_months > len(monthly):
            raise ValueError(f"Requested {args.history_months} months, but source has only {len(monthly)}.")
        monthly = monthly.tail(args.history_months).copy()
        quality = quality.reindex(monthly.index)
    study_raw = d[d.__date.isin(monthly.index)].drop(columns=["__date", "__target"])
    maker_month = pd.DataFrame()
    if "Maker" in raw.columns:
        dd = d[d.__date.isin(monthly.index)].copy()
        dd["Maker"] = dd.Maker.astype("string").str.strip()
        maker_month = dd.groupby(["__date", "Maker"]).__target.sum(min_count=1).rename("Demand").reset_index().rename(columns={"__date": "Month"})
    return raw, study_raw, monthly, macros, pd.DataFrame(column_audit), quality, pd.DataFrame(conflicts), maker_month, available_months

def build_features(data, macros, cfg):
    out = {}
    for lag in [1, 2, 3, 6, 12]:
        out[f"Demand_Lag_{lag}"] = data.Demand.shift(lag)
    for window in [3, 6]:
        out[f"Demand_Roll_{window}"] = data.Demand.shift(1).rolling(window).mean()
    out["Month"] = data.index.month
    out["Month_Sin"] = np.sin(2 * np.pi * data.index.month / 12)
    out["Month_Cos"] = np.cos(2 * np.pi * data.index.month / 12)
    for c in macros:
        # Forward filling only along TIME; leading gaps remain missing until
        # the training-only imputer. Never fill across different predictors.
        raw = data[c]
        if cfg.imputation == "baseline":
            past = raw.ffill()
        elif cfg.imputation in ("limited_1", "limited_3"):
            past = raw.ffill(limit=int(cfg.imputation[-1]))
        elif cfg.imputation == "seasonal":
            # Only past observed values; no future interpolation/backfill.
            past = raw.fillna(raw.shift(12))
        else:
            raise ValueError(cfg.imputation)
        observed_positions = pd.Series(np.where(raw.notna(), np.arange(len(raw)), np.nan), index=raw.index).ffill()
        age = pd.Series(np.arange(len(raw)), index=raw.index) - observed_positions
        for lag in [1, 3, 6, 12]:
            effective_lag = lag + cfg.release_lag - 1
            key = f"Macro::{c}::Lag_{effective_lag}"
            out[key] = past.shift(effective_lag)
            out[key + "::Originally_missing"] = raw.isna().astype(float).shift(effective_lag)
            out[key + "::Staleness"] = age.shift(effective_lag)
    return pd.DataFrame(out, index=data.index).replace([np.inf, -np.inf], np.nan)

def feature_groups(cols, macros):
    groups = {
        "Demand_history": [c for c in cols if c.startswith("Demand_")],
        "Calendar": [c for c in cols if c.startswith("Month")],
        "All_macro": [c for c in cols if c.startswith("Macro::")],
    }
    groups.update({f"Macro_{i + 1}": [c for c in cols if c.startswith(f"Macro::{m}::")] for i, m in enumerate(macros)})
    return {k: v for k, v in groups.items() if v}

def supervised(history, macros, cfg, cols=None):
    x = build_features(history, macros, cfg)
    # Structural warm-up is separate from macro missingness; keep every
    # observed target month after the longest demand lag (12 months).
    x = x.iloc[12:]
    if cols is not None:
        x = x.reindex(columns=cols)
    y = history.Demand.reindex(x.index)
    observed = y.notna()
    return x.loc[observed], y.loc[observed]

class TrainingMedianImputer(BaseEstimator, TransformerMixin):
    """Learn medians from this fit only; omit wholly unavailable features.
    Emit a missing flag for every retained feature, including prediction-only gaps.
    """
    def fit(self, X, y=None):
        a = X.to_numpy(dtype=float, na_value=np.nan) if isinstance(X, pd.DataFrame) else np.asarray(X, float)
        self.keep_ = np.isfinite(a).any(axis=0)
        self.statistics_ = np.nanmedian(a[:, self.keep_], axis=0)
        if not self.keep_.any():
            raise ValueError("No observed training features")
        return self
    def transform(self, X):
        a = (X.to_numpy(dtype=float, na_value=np.nan) if isinstance(X, pd.DataFrame) else np.asarray(X, float))[:, self.keep_]
        missing = ~np.isfinite(a)
        return np.hstack([np.where(missing, self.statistics_, a), missing.astype(float)])
    def get_feature_names_out(self, input_features=None):
        names = np.asarray(input_features, object)[self.keep_]
        return np.r_[names, ["missingindicator_" + str(c) for c in names]]

def make_estimator(name, cfg, alpha=None):
    imputer = TrainingMedianImputer()
    if name == "Ridge":
        return Pipeline([("impute", imputer), ("scale", StandardScaler()), ("model", Ridge(alpha=cfg.ridge_alpha if alpha is None else alpha))])
    if name == "Random_Forest":
        model = RandomForestRegressor(n_estimators=cfg.trees, max_depth=8, min_samples_leaf=2, random_state=cfg.seed, n_jobs=2)
    elif name == "XGBoost":
        if XGBRegressor is None:
            raise RuntimeError("Install xgboost or run with --skip-xgb.")
        model = XGBRegressor(n_estimators=cfg.trees, max_depth=3, learning_rate=.03, subsample=.8, colsample_bytree=.8, objective="reg:squarederror", random_state=cfg.seed, n_jobs=2)
    else:
        raise ValueError(name)
    return Pipeline([("impute", imputer), ("model", model)])

def forecast(history, steps, name, macros, cfg, alpha=None, cols=None, future_macro=None):
    """Receive PAST ONLY. All unknown demand values are recursively predicted."""
    if len(history) < 24:
        raise ValueError("At least 24 historical months required.")
    dates = pd.date_range(history.index[-1] + pd.offsets.MonthBegin(), periods=steps, freq="MS")
    if name == "Seasonal_Naive":
        values = history.Demand.tolist()
        result = []
        for _ in dates:
            result.append(float(values[-12])); values.append(result[-1])
        return pd.Series(result, index=dates), None, None
    if name == "SARIMA":
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")
            fit = SARIMAX(history.Demand, order=(1, 1, 1), seasonal_order=(1, 1, 1, 12), enforce_stationarity=False, enforce_invertibility=False).fit(disp=False, maxiter=150)
        if not fit.mle_retvals.get("converged", True):
            LOG.warning("SARIMA did not converge at origin %s; inspect forecast reliability.", history.index[-1].strftime("%Y-%m"))
        pred = np.maximum(0, np.asarray(fit.forecast(steps), dtype=float))
        if not np.isfinite(pred).all():
            raise ValueError("SARIMA returned nonfinite forecasts.")
        return pd.Series(pred, index=dates), fit, None
    x, y = supervised(history, macros, cfg, cols)
    if len(y) < 12 or x.shape[1] == 0:
        raise ValueError("Insufficient supervised training rows or predictors.")
    fit = make_estimator(name, cfg, alpha)
    fit.fit(x, y)
    recursive = history.copy()
    result = []
    for date in dates:
        recursive.loc[date, "Demand"] = np.nan
        for c in macros:
            supplied = np.nan
            if future_macro is not None and date in future_macro.index and c in future_macro:
                supplied = future_macro.loc[date, c]
            observed = history[c].dropna()
            recursive.loc[date, c] = float(supplied) if pd.notna(supplied) else np.nan
        xt = build_features(recursive, macros, cfg).loc[[date], x.columns]
        value = max(0., float(fit.predict(xt)[0]))
        if not np.isfinite(value):
            raise ValueError(f"Nonfinite {name} forecast at {date}.")
        recursive.loc[date, "Demand"] = value
        result.append(value)
    return pd.Series(result, index=dates), fit, x

def metrics(actual, prediction):
    a, p = np.asarray(actual, float), np.asarray(prediction, float)
    mask = np.isfinite(a) & np.isfinite(p)
    a, p = a[mask], p[mask]
    if not len(a):
        return {"N": 0, "MAE": np.nan, "RMSE": np.nan, "sMAPE_pct": np.nan, "R2": np.nan}
    error = a - p
    denom = np.abs(a) + np.abs(p)
    terms = np.divide(2 * np.abs(error), denom, out=np.zeros_like(error), where=denom > 0)
    total = np.sum((a - a.mean()) ** 2)
    return {"N": len(a), "MAE": np.mean(np.abs(error)), "RMSE": np.sqrt(np.mean(error ** 2)), "sMAPE_pct": 100 * terms.mean(), "R2": 1 - np.sum(error ** 2) / total if total > 0 and len(a) > 1 else np.nan}

def performance(frame, models):
    return pd.DataFrame([{"Model": m, **metrics(frame.Actual, frame[m])} for m in models]).sort_values("MAE").reset_index(drop=True)

def loss_test(actual, a, b, label, lag=3, loss="absolute"):
    y, pa, pb = np.asarray(actual, float), np.asarray(a, float), np.asarray(b, float)
    ok = np.isfinite(y) & np.isfinite(pa) & np.isfinite(pb)
    y, pa, pb = y[ok], pa[ok], pb[ok]
    ea, eb = np.abs(y - pa), np.abs(y - pb)
    d = ea - eb if loss == "absolute" else ea ** 2 - eb ** 2
    n = len(d)
    row = {"Comparison": label, "Loss": loss, "N_pairs": n, "Mean_loss_A_minus_B": d.mean() if n else np.nan,
           "HAC_lags": min(lag, max(n - 2, 0)), "HAC_z": np.nan, "HAC_p": np.nan,
           "Paired_t_p_sensitivity": np.nan, "Inference": "Exploratory; small/dependent time-series sample; not a formal DM test"}
    if n < 4:
        return row
    # An intercept-only HAC regression tests mean(d)=0 with Bartlett weights.
    fit = sm.OLS(d, np.ones((n, 1))).fit(cov_type="HAC", cov_kwds={"maxlags": row["HAC_lags"], "use_correction": True})
    if fit.bse[0] > 0:
        row.update(HAC_z=float(fit.tvalues[0]), HAC_p=float(fit.pvalues[0]))
    sd = d.std(ddof=1)
    if sd > 0:
        row["Paired_t_p_sensitivity"] = float(2 * t.sf(abs(d.mean() / (sd / np.sqrt(n))), n - 1))
    return row

def adjust_tests(rows):
    df = pd.DataFrame(rows)
    if df.empty:
        return df
    df["Holm_p"] = np.nan
    good = df.HAC_p.notna()
    if good.any():
        df.loc[good, "Holm_p"] = multipletests(df.loc[good, "HAC_p"], method="holm")[1]
    df["Decision_at_05"] = np.where(df.Holm_p.isna(), "Not estimable", np.where(df.Holm_p < .05, "Reject equality (exploratory)", "Fail to reject equality"))
    df["Direction"] = np.where(df.Mean_loss_A_minus_B < 0, "A lower observed loss", np.where(df.Mean_loss_A_minus_B > 0, "A higher observed loss", "Equal observed loss"))
    return df

def validation_origins(n, cfg):
    end = n - cfg.horizon
    if end < cfg.min_train:
        raise ValueError("Not enough development history for 12-month inner validation; reduce --min-train explicitly.")
    origins = list(range(cfg.min_train, end + 1, cfg.origin_step))
    if origins[-1] != end:
        origins.append(end)
    return origins

def inner_validation(development, macros, cfg, models):
    records, grid = [], []
    for origin in validation_origins(len(development), cfg):
        LOG.info("Inner validation origin %s (%d training months)", development.index[origin - 1].strftime("%Y-%m"), origin)
        hist = development.iloc[:origin]
        actual = development.Demand.iloc[origin:origin + cfg.horizon]
        for model in models:
            pred, _, _ = forecast(hist, cfg.horizon, model, macros, cfg, alpha=10.)
            for h, (date, value) in enumerate(pred.items(), 1):
                records.append({"Origin": hist.index[-1], "Month": date, "Horizon": h, "Model": model, "Actual": actual.loc[date], "Prediction": value})
        for alpha in [1., 10., 100.]:
            if alpha == 10:
                pred = pd.Series([r["Prediction"] for r in records if r["Origin"] == hist.index[-1] and r["Model"] == "Ridge"], index=actual.index)
            else:
                pred, _, _ = forecast(hist, cfg.horizon, "Ridge", macros, cfg, alpha=alpha)
            for date, value in pred.items():
                grid.append({"Origin": hist.index[-1], "Month": date, "Alpha": alpha, "Actual": actual.loc[date], "Prediction": value})
    raw = pd.DataFrame(records)
    grid = pd.DataFrame(grid)
    tuning = pd.DataFrame([{"Alpha": a, **metrics(g.Actual, g.Prediction)} for a, g in grid.groupby("Alpha")]).sort_values("MAE")
    best_alpha = float(tuning.iloc[0].Alpha)
    selected_ridge = grid[grid.Alpha == best_alpha].copy()
    raw = raw[raw.Model != "Ridge"]
    selected_ridge["Model"] = "Ridge"
    # Restore horizon without guessing from overlapping target dates.
    selected_ridge["Horizon"] = ((selected_ridge.Month.dt.year - selected_ridge.Origin.dt.year) * 12 + selected_ridge.Month.dt.month - selected_ridge.Origin.dt.month)
    raw = pd.concat([raw, selected_ridge.drop(columns="Alpha")], ignore_index=True)
    wide = raw.pivot(index=["Origin", "Month", "Horizon"], columns="Model", values="Prediction").reset_index()
    truth = raw.groupby(["Origin", "Month", "Horizon"]).Actual.first().reset_index()
    wide = wide.merge(truth, on=["Origin", "Month", "Horizon"], validate="one_to_one")
    table = performance(wide, models)
    inv = 1 / table.set_index("Model").MAE.clip(lower=1e-9)
    weights = (inv / inv.sum()).to_dict()
    wide["Ensemble"] = sum(weights[m] * wide[m] for m in models)
    table = performance(wide, models + ["Ensemble"])
    table["N_origins"] = wide.Origin.nunique()
    table["Unique_target_months"] = wide.Month.nunique()
    return wide, table, weights, best_alpha, tuning

def select_imputation(development, macros, cfg):
    records, audits = [], []
    candidates = ["baseline", "limited_1", "limited_3", "seasonal"]
    for method in candidates:
        candidate = replace(cfg, imputation=method)
        for origin in validation_origins(len(development), cfg):
            hist = development.iloc[:origin]
            pred, _, _ = forecast(hist, cfg.horizon, "Ridge", macros, candidate, alpha=10.)
            actual = development.Demand.reindex(pred.index)
            records.append({"Method": method, "Origin": hist.index[-1], **metrics(actual, pred)})
            audits.extend(imputation_audit(hist, macros, candidate, "validation_training"))
    folds = pd.DataFrame(records)
    summary = folds.groupby("Method", as_index=False).agg(Mean_MAE=("MAE", "mean"), Mean_RMSE=("RMSE", "mean"), SD_MAE=("MAE", "std"), Folds=("Origin", "count"))
    summary = summary.sort_values(["Mean_MAE", "Mean_RMSE", "Method"]).reset_index(drop=True)
    selected = summary.iloc[0].Method
    return selected, folds, summary, pd.DataFrame(audits)

def imputation_audit(history, macros, cfg, stage):
    features, _ = supervised(history, macros, cfg)
    rows = []
    for c in macros:
        raw = history[c]
        for lag in [1, 3, 6, 12]:
            lag += cfg.release_lag - 1
            key = f"Macro::{c}::Lag_{lag}"
            original = raw.shift(lag).reindex(features.index)
            treated = features[key]
            wholly_missing = treated.notna().sum() == 0
            rows.append({"Stage": stage, "Origin": history.index[-1], "Method": cfg.imputation, "Variable": c, "Lag": lag,
                         "Rows": len(features), "Observed": int(original.notna().sum()),
                         "Past_value_filled": int((original.isna() & treated.notna()).sum()),
                         "Median_filled": 0 if wholly_missing else int(treated.isna().sum()),
                         "Omitted_no_training_values": wholly_missing,
                         "Original_missing_months": int(raw.isna().sum()),
                         "Leading_missing_months": int(raw.notna().to_numpy().argmax()) if raw.notna().any() else len(raw)})
    return rows

OLS_EXCLUSIONS = []

def regression_table(monthly, macros, controlled=True, differenced=False):
    # Inferential regression uses observed macro values, not imputed pseudo-data.
    block = monthly[["Demand"] + macros].diff() if differenced else monthly[["Demand"] + macros].copy()
    complete = block.dropna()
    if len(complete) < len(macros) + (14 if controlled else 4):
        return pd.DataFrame(), pd.DataFrame(), "Insufficient observed complete months."
    means, scales = complete[macros].mean(), complete[macros].std(ddof=0).replace(0, 1)
    x = (complete[macros] - means) / scales
    if controlled:
        x["Trend"] = np.arange(len(monthly))[monthly.index.get_indexer(complete.index)]
        for m in range(2, 13):
            x[f"Month_{m}"] = (complete.index.month == m).astype(float)
    x = sm.add_constant(x, has_constant="add").astype(float)
    specification = f"controlled={controlled}; differenced={differenced}"
    # Predefined exclusions of alternative bases/accounting totals; keep components.
    redundant_tokens = ["(2012=100)", "(2012=100", "netforeign", "netportfolio", "totalinvestment", "tradebalance", "rurallabour"]
    removed = []
    for c in macros:
        n = normalize_name(c)
        if any(token in n for token in redundant_tokens):
            removed.append((c, "Predefined alternative index/accounting redundancy"))
    x = x.drop(columns=[c for c, _ in removed], errors="ignore")
    # Scale controls too before numerical diagnostics and covariance calculation.
    for c in x.columns:
        if c != "const" and c not in macros:
            sd = x[c].std(ddof=0)
            if sd > 0:
                x[c] = (x[c] - x[c].mean()) / sd
    while True:
        a = x.to_numpy()
        _, r, piv = qr(a, mode="economic", pivoting=True)
        diag = np.abs(np.diag(r))
        rank = int((diag > diag.max() * 1e-8).sum())
        if rank < x.shape[1]:
            candidates = [x.columns[i] for i in piv[rank:] if x.columns[i] in macros]
            if not candidates:
                return pd.DataFrame(), pd.DataFrame(), "Rank-deficient controls; inference suppressed."
            drop = candidates[-1]
            reason = "Near-linear dependence: pivoted QR tolerance 1e-8"
        else:
            vifs = {c: variance_inflation_factor(a, i) for i,c in enumerate(x.columns) if c in macros}
            if not vifs or max(vifs.values()) <= 10:
                break
            drop = max(vifs, key=vifs.get)
            reason = f"VIF > 10 (observed {vifs[drop]:.3g}); exploratory design-based pruning"
        removed.append((drop, reason))
        x = x.drop(columns=drop)
    for c, reason in removed:
        OLS_EXCLUSIONS.append({"Specification": specification, "Variable": c, "Reason": reason})
    macros = [c for c in macros if c in x]
    condition = np.linalg.cond(x.to_numpy())
    if condition > 1e4 or len(complete) <= x.shape[1] + 5:
        return pd.DataFrame(), pd.DataFrame(), f"Unstable/insufficient residual degrees of freedom; inference suppressed; condition={condition:.3g}."
    fit = sm.OLS(complete.Demand, x).fit()
    # Calendar-aware Newey-West: missing months are zero-score slots, so a
    # 12-month lag remains 12 calendar months even if complete cases have gaps.
    scores = pd.DataFrame(x.to_numpy() * fit.resid.to_numpy()[:, None], index=complete.index).reindex(monthly.index, fill_value=0).to_numpy()
    pinv = np.linalg.pinv(x.to_numpy(), rcond=1e-10)
    bread = pinv @ pinv.T
    meat = scores.T @ scores
    lag = min(12, len(monthly) - 1)
    for j in range(1, lag + 1):
        cross = scores[j:].T @ scores[:-j]
        meat += (1 - j / (lag + 1)) * (cross + cross.T)
    cov = bread @ meat @ bread * len(complete) / (len(complete) - x.shape[1])
    se = np.sqrt(np.maximum(np.diag(cov), 0))
    z = np.divide(fit.params.to_numpy(), se, out=np.full_like(se, np.nan), where=se > 0)
    p = 2 * norm.sf(np.abs(z))
    table = pd.DataFrame({"Variable": x.columns, "Coefficient_scaled": fit.params.to_numpy(), "HAC_SE_scaled": se, "HAC_z": z, "p_value": p})
    table["Coefficient_per_original_unit"] = table.Coefficient_scaled
    table["HAC_SE_per_original_unit"] = table.HAC_SE_scaled
    for c in macros:
        ix = table.Variable == c
        table.loc[ix, "Coefficient_per_original_unit"] /= scales[c]
        table.loc[ix, "HAC_SE_per_original_unit"] /= scales[c]
    # Intercept/controls are retained on centered/scaled-macro parameterization.
    table["CI_lower"] = table.Coefficient_per_original_unit - 1.96 * table.HAC_SE_per_original_unit
    table["CI_upper"] = table.Coefficient_per_original_unit + 1.96 * table.HAC_SE_per_original_unit
    table["Holm_p_macro_family"] = np.nan
    ix = table.Variable.isin(macros) & table.p_value.notna()
    if ix.any():
        table.loc[ix, "Holm_p_macro_family"] = multipletests(table.loc[ix, "p_value"], method="holm")[1]
    table["N_observed_months"] = len(complete)
    table["R2"] = fit.rsquared
    table["Condition_number"] = condition
    table["Inference_status"] = "Exploratory after design-based redundancy pruning; not causal"
    table["HAC_calendar_lags"] = lag
    table["Specification"] = ("first differences" if differenced else "levels") + (" + trend/month controls" if controlled else " (uncontrolled sensitivity)")
    vif = []
    for i, c in enumerate(x.columns):
        if c in macros:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                v = variance_inflation_factor(x.to_numpy(), i)
            vif.append({"Variable": c, "VIF": v})
    note = f"Observed complete months={len(complete)}; predictors including intercept={x.shape[1]}; calendar-aware HAC lag={lag}; normal approximation; associations are not causal."
    return table, pd.DataFrame(vif), note

