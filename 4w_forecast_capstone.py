# STATISTICAL SAMPLE-SIZE PLANNING: assumptions, not achieved time-series power.
# References: https://docs.scipy.org/doc/scipy/reference/generated/scipy.stats.nct.html
#             https://docs.scipy.org/doc/scipy/reference/generated/scipy.stats.ncf.html
from scipy.stats import nct, ncf, f as f_distribution

POWER_ALPHA = 0.05
POWER_TARGET = 0.80
POWER_PAIRED_EFFECT = 0.50  # Prespecified |mean paired difference| / SD(difference).
POWER_PARTIAL_F2 = 0.15    # Prespecified incremental explained-variance effect.
POWER_MAX_N = 100000

def independent_paired_power(n, alpha, effect):
    """Exact two-sided noncentral-t power under independent normal differences."""
    if n < 2:
        return np.nan
    critical = t.ppf(1 - alpha / 2, n - 1)
    noncentrality = np.sqrt(n) * abs(effect)
    return float(nct.sf(critical, n - 1, noncentrality)
                 + nct.cdf(-critical, n - 1, noncentrality))

def independent_partial_f_power(n, alpha, effect, parameters, tested=1):
    """Idealized fixed-design partial-F power; k includes the intercept."""
    if n <= parameters:
        return np.nan
    critical = f_distribution.ppf(1 - alpha, tested, n - parameters)
    return float(ncf.sf(critical, tested, n - parameters, n * effect))

def minimum_power_n(power_function, minimum):
    if not (0 < POWER_TARGET < 1 and 0 < POWER_ALPHA < 1):
        raise ValueError('Power target and family alpha must be between zero and one.')
    # Bracket then search integer n; never modify the observed data to reach n.
    lo, hi = minimum - 1, minimum
    while power_function(hi) < POWER_TARGET:
        lo, hi = hi, hi * 2
        if hi > POWER_MAX_N:
            hi = POWER_MAX_N
            if power_function(hi) < POWER_TARGET:
                raise ValueError('Required sample exceeds POWER_MAX_N; revise planning inputs.')
            break
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if power_function(mid) >= POWER_TARGET:
            hi = mid
        else:
            lo = mid
    return hi

def build_statistical_sample_plan(actual_specs, ols_parameters, ols_macro_tests,
                                  historical_months, complete_ols_months,
                                  annual_min_history=60, annual_step=12):
    """One reporting row per RQ/task; dynamic family sizes and actual counts."""
    if POWER_PAIRED_EFFECT <= 0 or POWER_PARTIAL_F2 <= 0:
        raise ValueError('Planning effects must be positive and prespecified.')
    output = []
    for rq, task, actual, comparisons in actual_specs:
        comparisons = max(1, int(comparisons))
        alpha = POWER_ALPHA / comparisons  # conservative Bonferroni planning
        regression = rq == 'RQ3'
        if regression:
            if ols_parameters is None or ols_macro_tests < 1:
                output.append(dict(RQ=rq, Task=task, Actual_N=int(actual),
                                   Status='OLS inference unavailable; no sample benchmark computed'))
                continue
            comparisons = int(ols_macro_tests)
            alpha = POWER_ALPHA / comparisons
            power_fn = lambda n: independent_partial_f_power(
                n, alpha, POWER_PARTIAL_F2, ols_parameters)
            required = minimum_power_n(power_fn, ols_parameters + 1)
            df = required - ols_parameters
            critical = f_distribution.ppf(1 - alpha, 1, df)
            noncentrality = required * POWER_PARTIAL_F2
            formula = 'df2=n-k; lambda=n*f2; c=F.ppf(1-alpha,1,n-k); power=ncf.sf(c,1,n-k,lambda)'
            substitution = (f'n={required}; k={ols_parameters}; df2={df}; '
                            f'lambda={required}*{POWER_PARTIAL_F2}={noncentrality:.6f}; c={critical:.6f}')
            effect = POWER_PARTIAL_F2
            method = 'Independent-error partial-F planning (one coefficient; not HAC power)'
        else:
            power_fn = lambda n: independent_paired_power(n, alpha, POWER_PAIRED_EFFECT)
            required = minimum_power_n(power_fn, 2)
            df = required - 1
            critical = t.ppf(1 - alpha / 2, df)
            noncentrality = POWER_PAIRED_EFFECT * np.sqrt(required)
            formula = 'df=n-1; lambda=effect*sqrt(n); c=t.ppf(1-alpha/2,df); power=nct.sf(c,df,lambda)+nct.cdf(-c,df,lambda)'
            substitution = (f'n={required}; df={df}; lambda={POWER_PAIRED_EFFECT}*sqrt({required})'
                            f'={noncentrality:.6f}; c={critical:.6f}')
            effect = POWER_PAIRED_EFFECT
            method = 'Independent paired-difference noncentral-t planning (not HAC power)'
        calendar_allowance = np.nan
        if regression and complete_ols_months > 0:
            calendar_allowance = int(np.ceil(required * historical_months / complete_ols_months))
        elif task == 'Annual origin mean losses':
            calendar_allowance = annual_min_history + required * annual_step
        actual_power = power_fn(int(actual)) if actual > 0 else np.nan
        output.append(dict(
            RQ=rq, Task=task, Method=method, Actual_N=int(actual),
            Planning_comparisons=comparisons, Family_alpha=POWER_ALPHA,
            Per_test_alpha=alpha, Assumed_effect=effect, Target_marginal_power=POWER_TARGET,
            Required_independent_N=required, Independent_N_shortfall=max(0, required-int(actual)),
            Formula=formula, Numerical_substitution=substitution,
            Power_at_required_N=power_fn(required), Power_at_previous_N=power_fn(required-1),
            Conditional_IID_power_at_actual_N=actual_power,
            Hypothetical_calendar_months=calendar_allowance,
            Status=('Below independent-observation benchmark' if actual < required else
                    'Count reaches IID benchmark; temporal power remains unestablished'),
            Interpretation='Planning effects are assumptions, not fitted effect estimates. Actual months/origins may be dependent. No achieved HAC/Holm power or adequate-power claim. Calendar allowance is hypothetical, not a new split.'))
    return pd.DataFrame(output)

