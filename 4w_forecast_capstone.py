def smape(y_true, y_pred):
    a, p = np.asarray(y_true, float), np.asarray(y_pred, float)
    denom = np.abs(a) + np.abs(p)
    return 100 * np.divide(2 * np.abs(a - p), denom, out=np.zeros_like(a), where=denom > 0).mean()

