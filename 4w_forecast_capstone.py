def dm_style_test(actual, pred1, pred2):
    """Legacy paired t sensitivity on squared loss; NOT a formal DM test."""
    actual = np.asarray(actual, dtype=float)
    pred1 = np.asarray(pred1, dtype=float)
    pred2 = np.asarray(pred2, dtype=float)
    e1 = actual - pred1
    e2 = actual - pred2
    loss1 = e1 ** 2
    loss2 = e2 ** 2
    d = loss1 - loss2
    n = len(d)
    if n < 3:
        return np.nan, np.nan
    mean_d = np.mean(d)
    sd_d = np.std(d, ddof=1)
    if sd_d == 0:
        return np.nan, np.nan
    se = sd_d / np.sqrt(n)
    statistic = mean_d / se
    p_value = 2 * t.sf(np.abs(statistic), df=n - 1)
    return statistic, p_value

def inverse_mae_weights(validation_results):
    maes = {}
    for model, values in validation_results.items():
        mae = values.get("MAE", np.nan)
        if np.isfinite(mae) and mae > 0:
            maes[model] = mae
    if len(maes) == 0:
        return {}
    inv = {model: 1.0 / mae for model, mae in maes.items()}
    total = sum(inv.values())
    weights = {model: value / total for model, value in inv.items()}
    return weights


